    UNIQUE KEY uk_solicitacao_ativa_por_aluno_escola (aluno_id, escola_id, ativa),
    KEY idx_solicitacao_aluno (aluno_id),
    KEY idx_solicitacao_escola (escola_id),
    KEY idx_solicitacao_status (status),
    KEY idx_solicitacao_ativa (ativa),
    CONSTRAINT fk_solicitacao_escola FOREIGN KEY (escola_id) REFERENCES escola (id),
    CONSTRAINT fk_solicitacao_aluno FOREIGN KEY (aluno_id) REFERENCES aluno (id),
    CONSTRAINT fk_solicitacao_responsavel FOREIGN KEY (responsavel_id) REFERENCES responsavel (id),
    CONSTRAINT fk_solicitacao_aluno_escola FOREIGN KEY (escola_id, aluno_id) REFERENCES aluno (escola_id, id),
    CONSTRAINT fk_solicitacao_responsavel_escola FOREIGN KEY (escola_id, responsavel_id) REFERENCES responsavel (escola_id, id)
) ENGINE=InnoDB;

