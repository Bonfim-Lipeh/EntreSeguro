CREATE TABLE solicitacao_retirada (
    id BIGINT NOT NULL AUTO_INCREMENT,
    escola_id BIGINT NOT NULL,
    aluno_id BIGINT NOT NULL,
    responsavel_id BIGINT NOT NULL,
    funcionario_id BIGINT NULL,
    status VARCHAR(30) NOT NULL,
    ativa TINYINT(1) NOT NULL DEFAULT 1,
    motivo VARCHAR(255) NULL,
    observacao VARCHAR(255) NULL,
    justificativa_rejeicao VARCHAR(500) NULL,
    motivo_excecao VARCHAR(30) NULL,
    qr_code_hash VARCHAR(255) NULL,
    qr_code_validado_em DATETIME NULL,
    data_solicitacao DATETIME NOT NULL,
    data_atendimento DATETIME NULL,
    data_conclusao DATETIME NULL,
    versao BIGINT NULL,
