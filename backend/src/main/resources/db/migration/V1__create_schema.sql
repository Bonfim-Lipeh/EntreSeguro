CREATE TABLE vinculo_aluno_responsavel (
    id BIGINT NOT NULL AUTO_INCREMENT,
    escola_id BIGINT NOT NULL,
    aluno_id BIGINT NOT NULL,
    responsavel_id BIGINT NOT NULL,
    tipo_relacao VARCHAR(30) NOT NULL,
    principal TINYINT(1) NOT NULL,
    ativo TINYINT(1) NOT NULL,
    validado_em DATETIME NULL,
    criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_vinculo_principal (escola_id, aluno_id, principal),
    KEY idx_vinculo_escola (escola_id),
    KEY idx_vinculo_aluno (aluno_id),
    KEY idx_vinculo_responsavel (responsavel_id),
    CONSTRAINT fk_vinculo_escola FOREIGN KEY (escola_id) REFERENCES escola (id),
    CONSTRAINT fk_vinculo_aluno FOREIGN KEY (aluno_id) REFERENCES aluno (id),
    CONSTRAINT fk_vinculo_responsavel FOREIGN KEY (responsavel_id) REFERENCES responsavel (id),
    CONSTRAINT fk_vinculo_aluno_escola FOREIGN KEY (escola_id, aluno_id) REFERENCES aluno (escola_id, id),
    CONSTRAINT fk_vinculo_responsavel_escola FOREIGN KEY (escola_id, responsavel_id) REFERENCES responsavel (escola_id, id)
) ENGINE=InnoDB;

