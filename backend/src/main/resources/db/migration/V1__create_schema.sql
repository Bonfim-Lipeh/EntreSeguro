CREATE TABLE escola (
    id BIGINT NOT NULL AUTO_INCREMENT,
    nome VARCHAR(150) NOT NULL,
    cnpj VARCHAR(18) NOT NULL,
    razao_social VARCHAR(200) NOT NULL,
    telefone VARCHAR(30) NULL,
    email VARCHAR(200) NULL,
    timezone VARCHAR(50) NOT NULL,
    status VARCHAR(30) NOT NULL,
    versao BIGINT NULL,
    criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_escola_cnpj (cnpj)
) ENGINE=InnoDB;

CREATE TABLE turma (
    id BIGINT NOT NULL AUTO_INCREMENT,
    escola_id BIGINT NOT NULL,
    nome VARCHAR(80) NOT NULL,
    nivel VARCHAR(50) NOT NULL,
    turno VARCHAR(30) NOT NULL,
    ano_letivo INT NOT NULL,
    status VARCHAR(30) NOT NULL,
    versao BIGINT NULL,
    criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_turma_escola_nome (escola_id, nome),
    KEY idx_turma_escola (escola_id),
    KEY idx_turma_status (status),
    CONSTRAINT fk_turma_escola FOREIGN KEY (escola_id) REFERENCES escola (id)
) ENGINE=InnoDB;

CREATE TABLE usuario (
    id BIGINT NOT NULL AUTO_INCREMENT,
    escola_id BIGINT NOT NULL,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(200) NOT NULL,
    senha_hash VARCHAR(255) NOT NULL,
    perfil VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL,
    versao BIGINT NULL,
    criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_usuario_email (email),
    KEY idx_usuario_escola (escola_id),
    KEY idx_usuario_perfil (perfil),
    CONSTRAINT fk_usuario_escola FOREIGN KEY (escola_id) REFERENCES escola (id)
) ENGINE=InnoDB;

CREATE TABLE aluno (
    id BIGINT NOT NULL AUTO_INCREMENT,
    escola_id BIGINT NOT NULL,
    turma_id BIGINT NOT NULL,
    nome VARCHAR(150) NOT NULL,
    data_nascimento DATE NOT NULL,
    matricula VARCHAR(50) NOT NULL,
    documento_criptografado VARCHAR(512) NOT NULL,
    documento_hmac VARCHAR(128) NOT NULL,
    status VARCHAR(30) NOT NULL,
    versao BIGINT NULL,
    criado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_aluno_escola_matricula (escola_id, matricula),
    UNIQUE KEY uk_aluno_escola_chave (escola_id, id),
    KEY idx_aluno_escola (escola_id),
    KEY idx_aluno_turma (turma_id),
    KEY idx_aluno_status (status),
    CONSTRAINT fk_aluno_turma FOREIGN KEY (turma_id) REFERENCES turma (id),
    CONSTRAINT fk_aluno_escola FOREIGN KEY (escola_id) REFERENCES escola (id)
) ENGINE=InnoDB;

CREATE TABLE responsavel (
    id BIGINT NOT NULL AUTO_INCREMENT,
    escola_id BIGINT NOT NULL,
